//Literals

let count = 42; //Integer literal
let negative = -100; //Negative integer literal
let zero = 0; //Integer literal

let h = 0xFF; // Hexadecimal literal
let color_hex = 0xFF0000; // Hexadecimal literal for red color
let octal = 0o77; // Octal literal
let million = 1e6; // Exponential notation literal (1*10^6)
let tiny = 1.5e-4; // Exponential notation literal (1.5*10^-4)


console.log(typeof count); // output: number
console.log(typeof negative); // output: number
console.log(typeof zero); // output: number

console.log(typeof h); // output: number
console.log(typeof color_hex); // output: number
console.log(typeof octal); // output: number
console.log(typeof million); // output: number
console.log(typeof tiny); // output: number